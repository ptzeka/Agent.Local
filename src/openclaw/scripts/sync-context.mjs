#!/usr/bin/env node
// Copies the project's canonical agent-context file into the openclaw workspace
// as AGENTS.md so openclaw's bootstrap injection picks it up as Project Context.
// Source path can be overridden with AGENT_CONTEXT_FILE (matches the convention
// used by src/agent's context-loader).

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..", "..", "..");

const sourcePath = resolveSourcePath();
const targetPath = path.resolve(
  scriptDir,
  "..",
  ".openclaw",
  "workspace",
  "AGENTS.md"
);

function resolveSourcePath() {
  const override = process.env.AGENT_CONTEXT_FILE?.trim();
  if (override) {
    return path.isAbsolute(override)
      ? path.resolve(override)
      : path.resolve(repoRoot, override);
  }
  return path.resolve(repoRoot, "src", "context", "agentcontext.md");
}

function toPosix(p) {
  return p.split(path.sep).join("/");
}

async function main() {
  let raw;
  try {
    raw = await fs.readFile(sourcePath, "utf8");
  } catch (err) {
    if (err && err.code === "ENOENT") {
      console.log(
        `[sync-context] source missing, skipping: ${toPosix(
          path.relative(repoRoot, sourcePath)
        )}`
      );
      return;
    }
    throw err;
  }

  const sourceRel = toPosix(path.relative(repoRoot, sourcePath));
  const header =
    `<!-- AUTO-GENERATED by src/openclaw/scripts/sync-context.mjs -->\n` +
    `<!-- Source: ${sourceRel} — do not edit AGENTS.md directly. -->\n\n`;
  const out = header + raw.replace(/^\s+/, "");

  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, out, "utf8");

  console.log(
    `[sync-context] ${sourceRel} → ${toPosix(
      path.relative(repoRoot, targetPath)
    )} (${out.length} chars)`
  );
}

main().catch((err) => {
  console.error(`[sync-context] failed: ${err?.message ?? err}`);
  process.exit(1);
});
